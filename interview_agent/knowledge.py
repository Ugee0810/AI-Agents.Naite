SPEAKING_RULES = """
## 面接での話し方ルール（必ず守ること）

1. **結論ファースト構成**: 結論 → 具体例 or 理由 → 結論 の3段構成で回答を構成すること。
2. **時間管理**: 回答は1分〜1分半に収めること。1分半を超えると「質問とずれた話をしている」と判断される。
3. **回答の開始と終了**: 「はい」で答え始め、「以上です」で締める。一問一答以外は必須。
4. **質問の要約**: 相手の質問を要約してから回答する。
   - NG: 「好きな食べ物は？」→「はい、ラーメンです」
   - OK: 「好きな食べ物は？」→「はい、好きな食べ物はラーメンです」
5. **ポジティブワード変換**: ネガティブワードは絶対使わない。
   - NG: 「興味ない」「苦手」
   - OK: 「前向きに頑張る」「自主的に取り組みたい」
6. **質問への直接回答**: 質問された内容のみに答える。転職理由を聞かれて志望動機を答えるなど、回答のズレを起こさない。
7. **キーワードで記憶**: 面接内容は単語で覚え、自分の言葉で話す。文章で暗記すると早口になり、忘れるリスクがある。
8. **印象の向上**: 適度な相槌、ハキハキした口調、相手の目を見てゆっくり話す。
"""

