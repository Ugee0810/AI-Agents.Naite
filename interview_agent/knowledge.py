TENSYOKU_RIYUU_RULES = """
## 転職理由の作成ルール

### 基本3原則
1. **継続性の証明**: 面接官に「末長く御社で働き続けられます」という想いを感じさせること。
2. **本音と建前の切り分け**: 建前はウソではなく、ポジティブで自分も納得いく理由。本音（基本ネガティブ）は面接では伝えない。
3. **戦略的に1つに絞る**: 志望理由から逆算して準備し、長期目線で語り、客観的に伝え、試行錯誤したことを伝える。

### 回答構成
1. 「大きく分けて2つあります」で切り出す
2. 1つ目は……（結論→理由）
3. 2つ目は……（結論→理由）

### シナリオ別ポジティブ変換パターン

#### 業界の成長性
- 「長期視点で考えて、より成長性のある業界で働きたい」
- 「個人の努力と業界の伸びの掛け算で成長速度は変わる」と伝える
- 現職での努力（相談回数を増やす等）も述べた上で環境の限界を説明

#### 年収・評価
- 年収・お金を連想させるワードを1番に出さない
- 「モチベーション高く働き続けることが難しい」から始める
- 実績→評価制度の問題→掛け合いの努力→転職決意の流れ

#### 残業・ハードワーク
- 「キャリア形成が難しい」から始める
- 具体的な数字（月70時間以上等）と許容ライン（40時間以内）を示す
- 自己研鑽との両立の観点で語る

#### 仕事内容の変更
- 前の仕事を否定しない
- 現職でのやりがい・実績を述べた上で、より難易度の高い挑戦への意欲を示す
- 社内異動の試みも述べる

### 絶対NGな転職理由
- **人間関係**: 「うちでも合わなかったら辞めるのでは」と思われる。改善しようがないため不可。
- **あいまいな理由**: プライベートの話が出た時点で見送り。本音と建前を考えること。
- **ブラック企業**: このワードは使用禁止。
- **パワハラ**: 主観的断定ワードは使用禁止。
"""

